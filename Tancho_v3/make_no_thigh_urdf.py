#!/usr/bin/env python3
"""Derive Tancho_v3_no_thigh.urdf from Tancho_v3.urdf.

The thigh links (meshes, collisions, mass) and joint_thigh_* are removed
entirely. Each calf (with its knee motor) mounts on base_link exactly at
the hip motor position, so the two motors span the original ~154 mm
outer width. joint_calf range becomes -90..+90 deg. Leg chain: base_link -> calf (revolute) -> wheel
(continuous). Tancho_v3.urdf is only read.
"""

from __future__ import annotations

import sys
import xml.etree.ElementTree as ET
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent
SRC = ROOT / "Tancho_v3.urdf"
DST = ROOT / "Tancho_v3_no_thigh.urdf"


def vec(text: str) -> np.ndarray:
    return np.array([float(v) for v in text.split()])


def fmt(v) -> str:
    return " ".join(f"{x:.12g}" for x in v)


def main(src: Path = SRC, dst: Path = DST) -> None:
    tree = ET.parse(src)
    robot = tree.getroot()
    robot.set("name", "Tancho_v3_no_thigh")
    links = {l.get("name"): l for l in robot.findall("link")}
    joints = {j.get("name"): j for j in robot.findall("joint")}

    for side in ("L", "R"):
        hip = joints[f"joint_thigh_{side}"]
        knee = joints[f"joint_calf_{side}"]
        assert not vec(hip.find("origin").get("rpy")).any()
        hip_xyz = vec(hip.find("origin").get("xyz"))
        knee.find("origin").set("xyz", fmt(hip_xyz))
        knee.find("parent").set("link", "base_link")
        knee.find("limit").set("lower", f"{-np.pi / 2:.6f}")
        knee.find("limit").set("upper", f"{np.pi / 2:.6f}")

        robot.remove(links[f"thigh_{side}"])
        robot.remove(hip)

    robot.insert(
        0,
        ET.Comment(
            " Generated by make_no_thigh_urdf.py: thigh links and joints removed; "
            "calf mounts at the hip motor position, range +-90 deg. Legs are base_link -> calf -> wheel. "
        ),
    )
    ET.indent(tree, "  ")
    tree.write(dst, encoding="utf-8", xml_declaration=True)
    print(f"wrote {dst}")


if __name__ == "__main__":
    # Optional: make_no_thigh_urdf.py <src.urdf> <dst.urdf>
    main(*(Path(a) for a in sys.argv[1:3]))
